from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

_files: dict[str, str] = {}
_missing: list[str] = []


def text(path: str) -> str:
    if path not in _files:
        _files[path] = (ROOT / path).read_text(encoding="utf-8")
    return _files[path]


def replace(path: str, old: str, new: str, *, required: bool = True) -> None:
    current = text(path)
    count = current.count(old)
    if count == 0:
        if required:
            _missing.append(f"{path}: {old}")
        return
    _files[path] = current.replace(old, new)


def write_all() -> None:
    if _missing:
        details = "\n".join(f"- {item}" for item in _missing)
        raise SystemExit(f"Required copy was not found; no files were written:\n{details}")
    for path, content in _files.items():
        (ROOT / path).write_text(content, encoding="utf-8")
        print(f"updated {path}")


